const KEY = 'um-lang';
export function getLang() {
    try {
        return localStorage.getItem(KEY) === 'en' ? 'en' : 'zh';
    }
    catch {
        return 'zh';
    }
}
export function setLang(l) {
    try {
        localStorage.setItem(KEY, l);
    }
    catch { /* ignore */ }
    try {
        window.dispatchEvent(new CustomEvent('um-lang-change'));
    }
    catch { /* ignore */ }
}
